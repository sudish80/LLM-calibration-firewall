"""## Advanced Security Features
Implementing rate limiting and anomaly detection.
"""

class AdvancedFirewallFeatures:
    def __init__(self, firewall):
        self.firewall = firewall
        self.rate_limiter = {}

    def add_rate_limiting(self, user_id, max_requests=10, time_window=60):
        import time
        current_time = time.time()
        if user_id not in self.rate_limiter:
            self.rate_limiter[user_id] = {'count': 1, 'start_time': current_time}
            return True
        user_data = self.rate_limiter[user_id]
        if current_time - user_data['start_time'] > time_window:
            user_data.update({'count': 1, 'start_time': current_time})
            return True
        if user_data['count'] >= max_requests: return False
        user_data['count'] += 1
        return True

    def detect_anomalies(self, text):
        import re
        anomalies = []
        if re.search(r'([!?]){3,}', text): anomalies.append('Excessive punctuation')
        if len(text.split()) > 200: anomalies.append('Excessive length')
        return anomalies

