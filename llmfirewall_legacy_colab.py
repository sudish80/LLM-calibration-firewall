class LLMFirewall:
    def __init__(self, toxicity_threshold=0.5, sentiment_threshold=0.9):
        self.load_models()
        self.setup_filters(toxicity_threshold, sentiment_threshold)
        self.setup_patterns()

    def load_models(self):
        print("Loading models...")
        from transformers import pipeline
        import torch
        self.toxicity_model = pipeline("text-classification", model="unitary/toxic-bert", device=0 if torch.cuda.is_available() else -1)
        self.intent_model = pipeline("zero-shot-classification", model="facebook/bart-large-mnli", device=0 if torch.cuda.is_available() else -1)
        self.sentiment_model = pipeline("sentiment-analysis", model="distilbert-base-uncased-finetuned-sst-2-english", device=0 if torch.cuda.is_available() else -1)
        print("Models loaded successfully!")

    def setup_filters(self, toxicity_threshold, sentiment_threshold):
        self.filters = {'toxicity_threshold': toxicity_threshold, 'sentiment_threshold': sentiment_threshold}

    def setup_patterns(self):
        import re
        self.patterns = {
            'prompt_injection': [r'ignore.*previous.*instructions', r'forget.*training.*data', r'jailbreak.*bypass'],
            'sensitive_patterns': [r'\\b\\d{3}-\\d{2}-\\d{4}\\b', r'\\b\\d{4}\\s?\\d{4}\\s?\\d{4}\\s?\\d{4}\\b']
        }

    def detect_prompt_injection(self, text):
        import re
        return any(re.search(p, text.lower()) for p in self.patterns['prompt_injection'])

    def detect_pii(self, text):
        import re
        return any(re.search(p, text) for p in self.patterns['sensitive_patterns'])

    def moderate(self, text):
        results = {'input': text, 'allowed': True, 'reasons': []}

        # 1. Structural Checks (Strictly block PII and Injections always)
        if self.detect_pii(text):
            results['allowed'] = False
            results['reasons'].append('PII detected')
        if self.detect_prompt_injection(text):
            results['allowed'] = False
            results['reasons'].append('Prompt injection detected')

        # 2. Early Intent Detection for Educational Override
        intent = self.intent_model(text, ['educational', 'informative', 'malicious', 'dangerous', 'benign'])
        results['intent'] = intent
        top_intent = intent['labels'][0]
        edu_score = max(intent['scores'][intent['labels'].index('educational')],
                        intent['scores'][intent['labels'].index('informative')])

        # Educational override if score is high or it's the top intent
        is_educational = edu_score > 0.35 or top_intent in ['educational', 'informative']

        # 3. Toxicity and Sentiment Checks
        tox = self.toxicity_model(text)[0]
        sent = self.sentiment_model(text)[0]
        results['toxicity'], results['sentiment'] = tox, sent

        # Toxicity is always a hard block
        if tox['score'] > self.filters['toxicity_threshold']:
            results['allowed'] = False
            results['reasons'].append('Toxic content detected')

        # 4. Sentiment & Malicious Intent (Bypassed if educational)
        if not is_educational:
            if sent['label'] == 'NEGATIVE' and sent['score'] > self.filters['sentiment_threshold']:
                results['allowed'] = False
                results['reasons'].append('Extreme negative sentiment detected')
            if top_intent in ['malicious', 'dangerous']:
                results['allowed'] = False
                results['reasons'].append(f'Malicious intent detected ({top_intent})')

        return results

